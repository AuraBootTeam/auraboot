import { describe, it, expect } from 'vitest';
import { pdfBodyWithoutRunningBands } from '../../../../../tests/helpers/pdf-running-text';
const header = '华辰制造 · 项目预算';
const page = (body: string, number: number) =>
  `${header}\n${body}\n第 ${number} 页 2026/10/22\nGenerated by AuraBoot Platform\n`;
describe('independent PDF body extraction', () => {
  it('validates repeated headers and sequential footers before joining narrative', () => {
    expect(
      pdfBodyWithoutRunningBands(
        page('预算 ¥132,000.50\n正文前半', 1) + '\f' + page('正文后半', 2) + '\f',
        header,
      ),
    ).toBe('预算 ¥132,000.50\n正文前半\n正文后半');
  });
  it('retains band-like content inside the business body', () => {
    const body = `${header}\nGenerated by AuraBoot Platform\n第 1 页 2026/10/22\n预算复核`;
    expect(pdfBodyWithoutRunningBands(page(body, 1), header)).toBe(body);
  });
  it('rejects missing headers, wrong numbers, missing credits and empty pages', () => {
    expect(() =>
      pdfBodyWithoutRunningBands(page('正文', 1).replace(header, '错误标题'), header),
    ).toThrow('header');
    expect(() => pdfBodyWithoutRunningBands(page('正文', 2), header)).toThrow('number');
    expect(() =>
      pdfBodyWithoutRunningBands(
        page('正文', 1).replace('Generated by AuraBoot Platform', ''),
        header,
      ),
    ).toThrow('footer');
    expect(() => pdfBodyWithoutRunningBands(page('正文', 1) + '\f\f', header)).toThrow('Empty');
  });
  it('does not conceal a missing business amount or sentence', () => {
    const expected = '预算 ¥132,000.50\n必须保留的业务结论';
    expect(pdfBodyWithoutRunningBands(page(expected, 1), header)).toBe(expected);
    expect(pdfBodyWithoutRunningBands(page('预算 ¥132,000.50', 1), header)).not.toBe(expected);
  });
});
