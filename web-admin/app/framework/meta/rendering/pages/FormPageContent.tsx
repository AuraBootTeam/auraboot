export function FormPageContent(props: PageContentProps) {
  const {
    sidebarWidth,
    schema,
    tableName,
    token,
    initialValues,
    fieldPermissions,
    onSubmitOverride,
    onCancelOverride,
    showSuccessToast,
    showErrorToast,
    showInfoToast,
    showToast,
    formData,
    setFormData,
    initialFormData,
    setInitialFormData,
    fieldErrors,
    setFieldErrors,
    summaryErrors,
    setSummaryErrors,
    dirtyFieldsRef,
    clearFormDraftRef,
    searchParams,
    urlCommandCode,
    sourceRecordPid,
    routeRecordPid,
    isEditMode,
    recordPid,
  } = useFormPageState({ props });
  const {
    schemaFieldNames,
    urlDefaultValues,
    schemaDefaultValues,
    urlSeededModelCode,
    hasModelCodeAndKindFields,
    runtime,
    dataSourceManager,
    t,
    locale,
    navigate,
    hasPermission,
    kindCapabilities,
    pageContext,
  } = useFormPageRuntime({
    schema,
    isEditMode,
    searchParams,
    token,
    formData,
    recordPid,
    tableName,
    dirtyFieldsRef,
    setFormData,
  });
  const {
    mainRecordLoaded,
    fieldDataTypesRef,
    loadMainRecord,
    syncRuntimeFieldValue,
    submitting,
    setSubmitting,
    handleAction,
    loading,
    error,
    setError,
    clearFieldError,
  } = useFormRecord({
    isEditMode,
    recordPid,
    schema,
    dirtyFieldsRef,
    tableName,
    token,
    setFormData,
    setInitialFormData,
    runtime,
    formData,
    navigate,
    dataSourceManager,
    locale,
    t,
    showToast,
    setFieldErrors,
    setSummaryErrors,
  });
  const { modelFields, fieldMetaLoaded, aiFields, aiFill } = useFormMetadata({
    schema,
    fieldPermissions,
    locale,
    t,
    tableName,
    routeRecordPid,
    formData,
    setFormData,
    mainRecordLoaded,
    fieldDataTypesRef,
    token,
    syncRuntimeFieldValue,
  });
  const { validateFormBeforeSubmit, notifyValidationFailure } = useFormValidation({
    schema,
    recordPid,
    initialFormData,
    formData,
    pageContext,
    modelFields,
    t,
    locale,
    hasModelCodeAndKindFields,
    kindCapabilities,
    showErrorToast,
  });
  const { handleFormAction } = useFormSubmission({
    onCancelOverride,
    onSubmitOverride,
    setFieldErrors,
    setSummaryErrors,
    setError,
    handleAction,
    formData,
    schemaFieldNames,
    fieldMetaLoaded,
    showInfoToast,
    t,
    validateFormBeforeSubmit,
    notifyValidationFailure,
    setSubmitting,
    showErrorToast,
    recordPid,
    initialFormData,
    sourceRecordPid,
    modelFields,
    token,
    clearFormDraftRef,
    urlCommandCode,
    schema,
    dirtyFieldsRef,
    showSuccessToast,
    navigate,
    tableName,
    locale,
  });
  const {
    subTableData,
    setSubTableData,
    editDataLoaded,
    subTableBlocks,
    subTableColumnsMap,
    enhancedColumns,
  } = useFormChildren({
    isEditMode,
    schemaDefaultValues,
    urlDefaultValues,
    setFormData,
    recordPid,
    schema,
    loadMainRecord,
    initialValues,
    token,
    locale,
  });
  const {
    renderSmartField,
    customBlockRuntime,
    restorableDraft,
    discardDraft,
    handleRestoreDraft,
  } = useFormFields({
    formData,
    setFormData,
    pageContext,
    fieldErrors,
    syncRuntimeFieldValue,
    runtime,
    dirtyFieldsRef,
    clearFieldError,
    initialFormData,
    recordPid,
    tableName,
    token,
    locale,
    t,
    schema,
    isEditMode,
    onSubmitOverride,
    schemaDefaultValues,
    urlDefaultValues,
    clearFormDraftRef,
  });
  return renderFormPageView({
    schema,
    urlCommandCode,
    mainRecordLoaded,
    schemaFieldNames,
    fieldMetaLoaded,
    tableName,
    pageContext,
    hasPermission,
    dataSourceManager,
    aiFill,
    isEditMode,
    locale,
    t,
    onCancelOverride,
    onSubmitOverride,
    summaryErrors,
    error,
    restorableDraft,
    handleRestoreDraft,
    discardDraft,
    urlSeededModelCode,
    runtime,
    aiFields,
    customBlockRuntime,
    fieldErrors,
    fieldPermissions,
    modelFields,
    renderSmartField,
    subTableBlocks,
    enhancedColumns,
    subTableColumnsMap,
    recordPid,
    formData,
    token,
    editDataLoaded,
    subTableData,
    setSubTableData,
    sidebarWidth,
    handleFormAction,
    loading,
    submitting,
  });
}
