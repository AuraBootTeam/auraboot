export interface BrandingConfig {
  mode: 'community' | 'commercial';
  productName: string;
  platformName: string;
  logoUrl: string;
  faviconUrl: string;
  favicon32Url: string;
  appleTouchIconUrl: string;
  manifestUrl: string;
  websiteUrl: string;
  docsUrl: string;
  supportUrl: string;
  sourceUrl: string;
  commercialContactUrl: string;
  licenseName: string;
  licenseUrl: string;
  copyrightHolder: string;
  aurabootCopyrightHolder: string;
  poweredByText: string;
  generatedByText: string;
  /**
   * Optional login-story copy (deployment-specific vertical, e.g. a school
   * product). When present the auth pages render this instead of the
   * platform-default feature tiles; every field is independently optional.
   */
  loginBadge?: string;
  loginHeadline?: string;
  loginHeadlineEm?: string;
  loginLead?: string;
  loginHeroUrl?: string;
  loginFeatures?: string[];
  /**
   * Pure-wechat school deployment: the school-side login page renders only the
   * WeChat entry (no email/password channels). Platform admins use the separate
   * admin login route. Branding-level flag — applies when commercial branding resolves.
   */
  loginWechatOnly?: boolean;
  /**
   * Optional product-specific copy and channel choice for the no-tenant
   * onboarding page. Keeping this in signed deployment branding lets a
   * vertical product say "school" while the platform default remains
   * organization/workspace neutral.
   */
  tenantOnboarding?: TenantOnboardingBranding;
}

export type TenantJoinChannel = 'invite_code' | 'wechat_mini';

export interface TenantOnboardingBranding {
  entityLabel: string;
  industryCode?: string;
  postCreateRedirect?: string;
  selectionTitle: string;
  selectionLead: string;
  createTitle: string;
  createDescription: string;
  createCta: string;
  joinTitle: string;
  joinDescription: string;
  joinCta: string;
  joinChannel: TenantJoinChannel;
  miniProgramName?: string;
  miniProgramQrUrl?: string;
  joinSteps?: string[];
}

type TenantOnboardingDocument = TenantOnboardingBranding;

