/** Remove only independently verified running bands at each PDF page boundary. */
export function pdfBodyWithoutRunningBands(text: string, header: string): string {
  const normalize = (value: string) => value.replace(/\s/g, '');
  if (!header.trim()) throw Error('An exact expected running header is required');
  const pages = text.split('\f');
  if (!pages.at(-1)?.trim()) pages.pop();
  if (!pages.length || pages.some((page) => !page.trim())) throw Error('Empty PDF page');
  let date: string | undefined;
  return pages
    .map((page, index) => {
      const lines = page
        .split('\n')
        .map((line) => line.trim())
        .filter(Boolean);
      if (normalize(lines.shift() || '') !== normalize(header))
        throw Error('Running header mismatch');
      if (lines.pop() !== 'Generated by AuraBoot Platform') throw Error('Platform footer mismatch');
      const footer = lines.pop()?.match(/^第\s*(\d+)\s*页\s*(\d{4}\/\d{1,2}\/\d{1,2})$/);
      if (!footer || Number(footer[1]) !== index + 1) throw Error('Running page number mismatch');
      if (date && date !== footer[2]) throw Error('Running date mismatch');
      date = footer[2];
      return lines.join('\n');
    })
    .join('\n');
}
