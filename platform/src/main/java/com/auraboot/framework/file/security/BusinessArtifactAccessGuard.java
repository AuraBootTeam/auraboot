import org.springframework.stereotype.Component;
import org.springframework.transaction.annotation.Isolation;
import org.springframework.transaction.annotation.Propagation;
import org.springframework.transaction.annotation.Transactional;

import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.Objects;

/** Current intrinsic root authorization for generated bytes, independent of creator and relation lists. */
@Component
@RequiredArgsConstructor
public class BusinessArtifactAccessGuard {
    private final ExtensionRegistry extensions;
    private final CommandDefinitionMapper commands;
    private final DynamicDataService data;
    private final MetaModelService metadata;
    private final BusinessCommandRecordAuthorization authorization;
    private final CommandPublicOutputProjectionService projection;
    private final ObjectMapper json;

    @Transactional(propagation = Propagation.REQUIRES_NEW, readOnly = true, isolation = Isolation.REPEATABLE_READ)
    public void authorize(FileEntity file) {
        if (file == null || file.getArtifactAuthorization() == null) return;
        var stamp = BusinessArtifactAuthorization.parse(file.getArtifactAuthorization());
        if (!MetaContext.exists() || MetaContext.isImpersonating() || MetaContext.getCurrentMemberId() == null || MetaContext.getCurrentMemberId() <= 0
                || MetaContext.getCurrentUserId() == null || MetaContext.getCurrentUserId() <= 0
                || MetaContext.getCurrentUserPid() == null || MetaContext.getCurrentUserPid().isBlank()
                || !Objects.equals(stamp.tenantId(), MetaContext.getCurrentTenantId())
                || !Objects.equals(file.getTenantId(), stamp.tenantId()) || Boolean.TRUE.equals(file.getDeletedFlag())
                || !"success".equals(file.getStatus())
                || com.auraboot.framework.application.security.MachineDataAccessContext.isActive()
                || com.auraboot.framework.openplatform.service.InstalledIntegrationExecution.active()) throw BusinessArtifactAuthorization.denied();
        var handler = extensions.getBusinessResourceOwner(stamp.commandCode()).orElseThrow(BusinessArtifactAuthorization::denied);
        if (!(handler instanceof BusinessResourceAuthorization owner)) throw BusinessArtifactAuthorization.denied();
        Integer budget = owner.businessArtifactFields().get(stamp.rootField());
        if (budget == null || budget < 1 || budget > 67_108_864 || file.getFileSize() == null || file.getFileSize() < 1 || file.getFileSize() > budget
                || !owner.publicBusinessResourceFields().keySet().equals(stamp.models().keySet())
                || owner.publicBusinessResourceFields().entrySet().stream().anyMatch(entry -> !entry.getValue().equals(stamp.models().get(entry.getKey()).declared())))
            throw BusinessArtifactAuthorization.denied();
        var definition = commands.selectOne(new LambdaQueryWrapper<CommandDefinition>().eq(CommandDefinition::getTenantId, stamp.tenantId())
                .eq(CommandDefinition::getCode, stamp.commandCode()).eq(CommandDefinition::getIsCurrent, true)
                .eq(CommandDefinition::getDeletedFlag, false).eq(CommandDefinition::getStatus, "published"));
        if (definition == null || !stamp.rootModel().equals(definition.getModelCode()) || !stamp.commandCode().equals(definition.getCode())
                || !stamp.tenantId().equals(definition.getTenantId()) || !Boolean.TRUE.equals(definition.getIsCurrent())
                || Boolean.TRUE.equals(definition.getDeletedFlag()) || !"published".equals(definition.getStatus())) throw BusinessArtifactAuthorization.denied();
        var request = new CommandExecuteRequest(); request.setTargetRecordId(stamp.rootPid());
        var context = CommandPipelineContext.builder().commandCode(stamp.commandCode()).command(definition).request(request)
                .tenantId(stamp.tenantId()).userId(MetaContext.getCurrentUserId()).targetRecordReadable(true).build();
        try { context.setExecConfig(json.readValue(definition.getExecutionConfig(), new TypeReference<Map<String,Object>>() {})); }
        catch (JsonProcessingException | IllegalArgumentException failure) { throw BusinessArtifactAuthorization.denied(); }
        if (context.getExecConfig() == null) throw BusinessArtifactAuthorization.denied();
        Object configuredHandler = context.getExecConfig().get("handler");
        if (configuredHandler != null && (!(configuredHandler instanceof String code)
                || !stamp.commandCode().equals(code) && extensions.getCommandHandler(code).orElse(null) != handler))
            throw BusinessArtifactAuthorization.denied();
        var boundary = owner.businessBoundary();
        context.setAuthorizationVerdict(CommandAuthorizationVerdict.authorized(boundary.permissions().stream().findFirst().orElseThrow(BusinessArtifactAuthorization::denied)));
        var codes = BusinessResourcePermissionContract.require(context, owner);
        var modelDefinition = metadata.getModelDefinition(stamp.rootModel()).orElseThrow(BusinessArtifactAuthorization::denied);
        if (!"published".equalsIgnoreCase(modelDefinition.getStatus())) throw BusinessArtifactAuthorization.denied();
        Map<String,Object> root;
        try {
            // The row is evidence for the decision, not a public read. Only the stamped exact
            // root is borrowed; the complete grant/scope/field checks below still authorize bytes.
            root = MetaContext.runWithCommandPermitPlan("TARGET", null, stamp.rootModel(), stamp.rootPid(),
                    () -> data.getByIdForAuthorization(stamp.rootModel(), stamp.rootPid()));
        } catch (com.auraboot.framework.meta.exception.MetaRecordNotFoundException missing) {
            throw BusinessArtifactAuthorization.denied();
        }
        if (root == null || !stamp.rootPid().equals(root.get("pid")) || Boolean.TRUE.equals(root.get("deleted_flag"))
                || !stamp.tenantId().toString().equals(String.valueOf(root.get("tenant_id")))) throw BusinessArtifactAuthorization.denied();
        List<BusinessGrantDecision.Grant> grants = new ArrayList<>();
        // Every declared duty must have a complete current grant. A plain model reader is a
        // separate alternative, not a fabricated ability to execute the generating command.
        var decisions = codes.stream().map(code -> authorization.resolve(MetaContext.getCurrentMemberId(), List.of(code), stamp.rootModel(), root)).toList();
        if (decisions.stream().allMatch(decision -> decision.result().granted())) decisions.forEach(decision -> grants.addAll(decision.grants()));
        var read = authorization.resolveModelRead(MetaContext.getCurrentMemberId(), stamp.rootModel(), root);
        if (read.result().granted()) grants.addAll(read.grants());
        if (grants.isEmpty()) throw BusinessArtifactAuthorization.denied();
        var grant = new BusinessGrantDecision(PermissionResult.allow(List.of()), stamp.tenantId(), MetaContext.getCurrentUserId(),
                MetaContext.getCurrentMemberId(), stamp.rootModel(), stamp.rootPid(), grants);
        context.setBusinessGrantDecision(grant);
        context.setBusinessTargetAuthorization(new CommandPipelineContext.BusinessTargetAuthorization(stamp.commandCode(), stamp.rootModel(), stamp.rootPid(),
                boundary.targetAction(), stamp.tenantId(), MetaContext.getCurrentUserId(), MetaContext.getCurrentMemberId()));
        if (!stamp.rootBinding().keySet().equals(owner.businessArtifactRootBindingFields())
                || !stamp.rootBinding().isEmpty() && !stamp.rootBinding().equals(projection.prepareArtifactReadBinding(context,owner,root)))
            throw BusinessArtifactAuthorization.denied();
        var definitions = metadata.getModelFields(stamp.rootModel());
        if (definitions == null) throw BusinessArtifactAuthorization.denied();
        var field = definitions.stream().filter(candidate -> candidate != null && stamp.rootField().equals(candidate.getCode()))
                .findFirst().orElseThrow(BusinessArtifactAuthorization::denied);
        if (!"file".equalsIgnoreCase(field.getDataType())) throw BusinessArtifactAuthorization.denied();
        var current = projection.prepare(context, owner); var rootFields = current.models().get(stamp.rootModel());
        if (rootFields == null || !rootFields.readable().contains(stamp.rootField())
                || rootFields.policyMasks().stream().anyMatch(mask -> stamp.rootField().equals(mask.field()))
                || rootFields.detailMasks().stream().anyMatch(mask -> stamp.rootField().equals(mask.field()))
                || !stamp.permits(current)) throw BusinessArtifactAuthorization.denied();
    }
}
