-- Durable, tenant/model-scoped import migration receipts. No business values are retained.
CREATE TABLE ab_plugin_field_rename (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    plugin_pid VARCHAR(26) NOT NULL,
    model_pid VARCHAR(26) NOT NULL,
    model_code VARCHAR(128) NOT NULL,
    physical_table VARCHAR(128) NOT NULL,
    from_field VARCHAR(128) NOT NULL,
    to_field VARCHAR(128) NOT NULL,
    source_definition_sha256 CHAR(64) NOT NULL,
    target_definition_sha256 CHAR(64) NOT NULL,
    first_import_id VARCHAR(26) NOT NULL,
    state VARCHAR(16) NOT NULL CHECK (state = 'applied'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (tenant_id, model_pid, from_field, to_field),
    UNIQUE (tenant_id, model_pid, to_field),
    CHECK (from_field <> to_field)
);
CREATE INDEX ab_plugin_field_rename_physical ON ab_plugin_field_rename (physical_table, to_field);
CREATE TABLE ab_plugin_field_rename_row (
    migration_id BIGINT NOT NULL REFERENCES ab_plugin_field_rename(id),
    record_pid TEXT NOT NULL,
    applied_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (migration_id, record_pid)
);
