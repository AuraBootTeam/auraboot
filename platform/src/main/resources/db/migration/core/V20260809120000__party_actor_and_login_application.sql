-- Session context is independent from user.security_version. context_version is
-- rotated whenever the effective Actor changes so the previous JWT can be rejected.
ALTER TABLE ab_user_session
    ADD COLUMN IF NOT EXISTS application_id BIGINT,
    ADD COLUMN IF NOT EXISTS login_channel_id BIGINT,
    ADD COLUMN IF NOT EXISTS tenant_id BIGINT,
    ADD COLUMN IF NOT EXISTS tenant_member_id BIGINT,
    ADD COLUMN IF NOT EXISTS execution_scope VARCHAR(20),
    ADD COLUMN IF NOT EXISTS actor_party_id BIGINT,
    ADD COLUMN IF NOT EXISTS party_membership_id BIGINT,
    ADD COLUMN IF NOT EXISTS session_stage VARCHAR(30) NOT NULL DEFAULT 'onboarding',
    ADD COLUMN IF NOT EXISTS context_version BIGINT NOT NULL DEFAULT 1;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_user_session_application') THEN
        ALTER TABLE ab_user_session ADD CONSTRAINT fk_user_session_application
            FOREIGN KEY (application_id) REFERENCES ab_login_application (id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_user_session_login_channel') THEN
        ALTER TABLE ab_user_session ADD CONSTRAINT fk_user_session_login_channel
            FOREIGN KEY (login_channel_id) REFERENCES ab_login_channel (id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_user_session_member') THEN
        ALTER TABLE ab_user_session ADD CONSTRAINT fk_user_session_member
            FOREIGN KEY (tenant_id, tenant_member_id) REFERENCES ab_tenant_member (tenant_id, id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_user_session_actor_party') THEN
        ALTER TABLE ab_user_session ADD CONSTRAINT fk_user_session_actor_party
            FOREIGN KEY (tenant_id, actor_party_id) REFERENCES ab_party (tenant_id, id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_user_session_party_membership') THEN
        ALTER TABLE ab_user_session ADD CONSTRAINT fk_user_session_party_membership
            FOREIGN KEY (tenant_id, party_membership_id) REFERENCES ab_party_membership (tenant_id, id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_user_session_execution_scope') THEN
        ALTER TABLE ab_user_session ADD CONSTRAINT ck_user_session_execution_scope
            CHECK (execution_scope IS NULL OR execution_scope IN ('party', 'tenant', 'platform', 'system'));
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_user_session_stage') THEN
        ALTER TABLE ab_user_session ADD CONSTRAINT ck_user_session_stage
            CHECK (session_stage IN ('onboarding', 'actor_selection', 'ready', 'platform', 'tenant_admin'));
    END IF;
END $$;

