-- Single-business-tenant product model: retain tenant isolation and model business
-- participants as Party Actors.  Pre-auth login routing tables are deliberately
-- separate from tenant-scoped Party tables.

-- Composite keys are prerequisites for same-tenant foreign keys below.
CREATE UNIQUE INDEX IF NOT EXISTS uq_ab_tenant_member_tenant_id_id
    ON ab_tenant_member (tenant_id, id);

ALTER TABLE ab_role
    ADD COLUMN IF NOT EXISTS role_scope VARCHAR(20) NOT NULL DEFAULT 'tenant';

CREATE UNIQUE INDEX IF NOT EXISTS uq_ab_role_tenant_id_id_scope
    ON ab_role (tenant_id, id, role_scope);

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'ck_ab_role_role_scope'
    ) THEN
        ALTER TABLE ab_role
            ADD CONSTRAINT ck_ab_role_role_scope
            CHECK (role_scope IN ('platform', 'tenant', 'party'));
    END IF;
END $$;

