-- Explicit operator authorization to move one failed accepted receipt to current trusted fingerprints.
-- Original envelope, installation binding and request identity remain immutable.
CREATE TABLE ab_installed_integration_recovery (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pid VARCHAR(26) NOT NULL UNIQUE,
    tenant_id BIGINT NOT NULL,
    installation_pid VARCHAR(100) NOT NULL,
    source_code VARCHAR(64) NOT NULL,
    external_event_id VARCHAR(160) NOT NULL,
    durable_event_id VARCHAR(400) NOT NULL,
    request_pid VARCHAR(100) NOT NULL,
    envelope_sha256 CHAR(64) NOT NULL,
    binding_sha256 CHAR(64) NOT NULL,
    previous_command_sha256 CHAR(64) NOT NULL,
    previous_provider_sha256 VARCHAR(71) NOT NULL,
    command_sha256 CHAR(64) NOT NULL,
    provider_sha256 VARCHAR(71) NOT NULL,
    replay_count INTEGER NOT NULL CHECK(replay_count>=0),
    requested_by_pid VARCHAR(100) NOT NULL,
    reason VARCHAR(512) NOT NULL CHECK(BTRIM(reason)<>''),
    requested_at TIMESTAMPTZ NOT NULL,
    FOREIGN KEY(tenant_id,installation_pid,source_code,external_event_id)
        REFERENCES ab_installed_integration_receipt(tenant_id,installation_pid,source_code,external_event_id),
    UNIQUE(tenant_id,installation_pid,source_code,external_event_id,
           previous_command_sha256,previous_provider_sha256,replay_count)
);
CREATE INDEX idx_installed_integration_recovery_event
    ON ab_installed_integration_recovery(tenant_id,durable_event_id,requested_at DESC);
COMMENT ON TABLE ab_installed_integration_recovery IS
    'Append-only before/after fingerprints, actor, reason and replay version; no payload or credentials';
