-- Draft edits use optimistic revisions; external contracts are immutable snapshots.
CREATE TABLE ab_open_api_publication (
    tenant_id BIGINT NOT NULL,
    code VARCHAR(100) NOT NULL,
    draft JSONB NOT NULL,
    draft_revision BIGINT NOT NULL DEFAULT 1 CHECK (draft_revision > 0),
    active_version INTEGER,
    status VARCHAR(16) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'published', 'withdrawn')),
    updated_by_pid VARCHAR(64) NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (tenant_id, code)
);

CREATE TABLE ab_open_api_publication_snapshot (
    tenant_id BIGINT NOT NULL,
    code VARCHAR(100) NOT NULL,
    schema_version INTEGER NOT NULL CHECK (schema_version > 0),
    definition JSONB NOT NULL,
    published_by_pid VARCHAR(64) NOT NULL,
    published_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (tenant_id, code, schema_version),
    FOREIGN KEY (tenant_id, code) REFERENCES ab_open_api_publication(tenant_id, code)
);

ALTER TABLE ab_open_api_publication ADD CONSTRAINT fk_open_api_active_snapshot
    FOREIGN KEY (tenant_id, code, active_version)
    REFERENCES ab_open_api_publication_snapshot(tenant_id, code, schema_version);

CREATE TABLE ab_open_api_resource_grant (
    tenant_id BIGINT NOT NULL,
    installation_id BIGINT NOT NULL,
    resource_code VARCHAR(100) NOT NULL,
    policy JSONB NOT NULL,
    revision BIGINT NOT NULL DEFAULT 1 CHECK (revision > 0),
    updated_by_pid VARCHAR(64) NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (tenant_id, installation_id, resource_code),
    FOREIGN KEY (tenant_id, installation_id) REFERENCES ab_application_installation(tenant_id, id),
    FOREIGN KEY (tenant_id, resource_code) REFERENCES ab_open_api_publication(tenant_id, code)
);

CREATE TABLE ab_open_api_publication_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    resource_code VARCHAR(100) NOT NULL,
    installation_id BIGINT,
    action VARCHAR(24) NOT NULL CHECK (action IN ('draft', 'publish', 'withdraw', 'grant', 'revoke')),
    actor_pid VARCHAR(64) NOT NULL,
    revision BIGINT NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_open_api_publication_audit ON ab_open_api_publication_audit(tenant_id, resource_code, occurred_at DESC);

COMMENT ON TABLE ab_open_api_resource_grant IS 'Explicit per-installation row and field access; absence denies access';
