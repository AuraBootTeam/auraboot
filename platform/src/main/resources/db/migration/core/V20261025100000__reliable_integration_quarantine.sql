-- Preserve terminal failure evidence when an administrator explicitly stops delivery.
ALTER TABLE ab_integration_dead_letter
    DROP CONSTRAINT ab_integration_dead_letter_status_check;
ALTER TABLE ab_integration_dead_letter
    ADD CONSTRAINT ab_integration_dead_letter_status_check
    CHECK (status IN ('open', 'replayed', 'quarantined'));

CREATE TABLE ab_integration_dead_letter_quarantine (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pid VARCHAR(26) NOT NULL UNIQUE,
    outbox_id BIGINT NOT NULL UNIQUE REFERENCES ab_outbox(id),
    tenant_id BIGINT NOT NULL,
    event_id TEXT NOT NULL,
    correlation_id TEXT,
    replay_count INTEGER NOT NULL CHECK (replay_count >= 0),
    requested_by_pid TEXT NOT NULL CHECK (BTRIM(requested_by_pid) <> ''),
    reason VARCHAR(512) NOT NULL CHECK (BTRIM(reason) <> ''),
    requested_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_integration_quarantine_event UNIQUE (tenant_id, event_id)
);

CREATE INDEX idx_integration_quarantine_requested
    ON ab_integration_dead_letter_quarantine (tenant_id, requested_at DESC);

COMMENT ON TABLE ab_integration_dead_letter_quarantine IS
    'Append-only operator quarantine audit; original outbox remains failed, not delivered';
